export function normText(str: string): string {
  return String(str || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

export function getLocalPictoSvg(word: string): string {
  const normalized = normText(word);
  const emoji = LOCAL_EMOJIS[normalized] || LOCAL_EMOJIS[word.toLowerCase()] || '🖼️';
  const cleanLabel = word.length > 12 ? word.slice(0, 11) + '…' : word;

  return `<svg viewBox="0 0 100 100" class="w-full h-full select-none" role="img" aria-label="${word}">
    <rect width="100" height="100" rx="14" fill="#f8fafc" stroke="#cbd5e1" stroke-width="3"/>
    <text x="50" y="58" font-size="44" text-anchor="middle" dominant-baseline="middle">${emoji}</text>
    <text x="50" y="88" font-size="12" font-weight="600" text-anchor="middle" fill="#334155">${cleanLabel}</text>
  </svg>`;
}
